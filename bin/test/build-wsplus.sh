#!/bin/sh
# build-wsplus.sh — smoke test for bin/build-wsplus.py
#
# Asserts:
#   1. the bundler writes an executable wsplus file to the given dir
#   2. the emitted file parses as valid python
#   3. the bootstrap region (everything before the "original bin/wsplus" marker)
#      runs cleanly in a fresh namespace and registers lib.nanorc_highlight
#   4. calling load_highlighter against a NON-existent path (which forces the
#      fallback path) still yields the mtron syntax with rules, and the result
#      emits ANSI color when given a typical mtron line
#
# This test does NOT require the websockets pip package (it execs only the
# bootstrap region of the bundle, never the body which imports websockets), and
# does NOT talk to a server.  Run it:
#
#   sh bin/test/build-wsplus.sh
set -eu
cd "$(dirname "$(readlink -f "$0")")/../.."

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

python3 bin/build-wsplus.py "$TMP" >/dev/null

[ -f "$TMP/wsplus" ] || { echo "FAIL: no wsplus written to $TMP"; exit 1; }
[ -x "$TMP/wsplus" ] || { echo "FAIL: wsplus is not executable"; exit 1; }

python3 - "$TMP" <<'PY' || { echo "FAIL: bundle behavior check failed"; exit 1; }
import sys, ast
p = sys.argv[1] + "/wsplus"
txt = open(p, encoding="utf-8").read()
ast.parse(txt)                                    # 1) whole bundle parses
marker = "    ### original bin/wsplus (unmodified; regenerated by bin/build-wsplus.py) ###"
assert marker in txt, "marker missing — bundler layout changed without an update to this test"
ns = {"__name__": "_boot", "__builtins__": __builtins__}
exec(compile(txt.split(marker, 1)[0], "<boot>", "exec"), ns)   # 2) bootstrap runs
mod = ns["_M_nanorc_highlight"]                 # 3) the required dep is registered
hl = mod.load_highlighter("/definitely/not/a/nanorc/mtron.nanorc", "mtron")  # 4) fallback
assert hl.syntax.name == "mtron", "unexpected syntax name: %r" % hl.syntax.name
assert len(hl.syntax.rules) > 0, "no rules parsed from inlined nanorc"
out = hl.highlight_block("int::5 + /usr/x -> 3.14; 's'; true; [a=>b]")
assert "\x1b[" in out, "no ANSI escape in highlight output"
print("build-wsplus: OK (syntax=%r, rules=%d, ansi=yes)" % (hl.syntax.name, len(hl.syntax.rules)))
PY
echo "build-wsplus: all checks passed."
